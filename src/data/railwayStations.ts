/**
 * Search helper for railway stations
 */
export function searchRailwayStations(query: string): RailwayStationItem[] {
  if (!query || !query.trim()) return ALL_RAILWAY_STATIONS.slice(0, 30);
  const q = query.trim().toLowerCase();

  return ALL_RAILWAY_STATIONS.filter((item) => {
    return (
      item.code.toLowerCase().includes(q) ||
      item.station.toLowerCase().includes(q) ||
      item.city.toLowerCase().includes(q)
    );
  });
}
